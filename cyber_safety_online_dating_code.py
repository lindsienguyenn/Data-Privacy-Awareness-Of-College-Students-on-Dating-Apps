import re

# Define keywords as REGEX patterns
cs_patterns = [
    r"\bcomputer science\b",
    r"\bdata science\b",
    r"\bcomputer information systems\b",
    r"\bcs\b"   # matches "CS", "CS & Econ", etc. but NOT "Economics"
]

def is_cs_major(major):
    major = str(major).lower()
    return int(any(re.search(pattern, major) for pattern in cs_patterns))

df['cs_major'] = df['major'].apply(is_cs_major)

