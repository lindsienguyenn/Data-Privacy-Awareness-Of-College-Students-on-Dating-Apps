import pandas as pd

file_id = "1cXIZ8gyLgYvHikaa7_UNm2XDiIZAMbYu"
url = f"https://drive.google.com/uc?id={file_id}"
df = pd.read_csv(url)

df = df.apply(pd.to_numeric, errors='ignore')

cyber_risk_items = ['cyber_risk1', 'cyber_risk2', 'cyber_risk3', 'cyber_risk4', 'cyber_risk5']
loneliness_items = ['loneliness1', 'loneliness2', 'loneliness3', 'loneliness4']
social_support_items = ['social1', 'social2', 'social3', 'social4']
cyber_know_item = ['cyber_know']

variables = {
    "Cyber Risk": cyber_risk_items,
    "Loneliness": loneliness_items,
    "Social Support": social_support_items,
    "Cyber Knowledge": cyber_know_item,
}

zscore_results = pd.DataFrame()

for var_name, cols in variables.items():

    if len(cols) > 1:
        scores = df[cols].mean(axis=1)
    else:
        scores = df[cols[0]]

    z_scores = (scores - scores.mean()) / scores.std(ddof=1)

    zscore_results[var_name + "_z"] = z_scores

zscore_results

