from scipy.stats import ttest_ind

cs     = df[df["cs_major"] == 1]
non_cs = df[df["cs_major"] == 0]

def ttest_and_print(var_name, pretty_label):
    cs_vals     = cs[var_name].dropna()
    non_vals    = non_cs[var_name].dropna()
    t_stat, p_val = ttest_ind(cs_vals, non_vals, equal_var=False)

    print(f"--- {pretty_label} ---")
    print(f"CS mean = {cs_vals.mean():.3f}, Non-CS mean = {non_vals.mean():.3f}")
    print(f"t({len(cs_vals)+len(non_vals)-2}) = {t_stat:.3f}, p = {p_val:.3f}")
    print()

#Cyber Risk (z)
